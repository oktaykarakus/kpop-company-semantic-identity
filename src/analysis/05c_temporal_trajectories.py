def calculate_trend_statistics(
    years: np.ndarray,
    values: np.ndarray,
) -> dict:
    """
    Calculate linear, robust, and rank-based temporal trend
    statistics.

    Parameters
    ----------
    years:
        Numeric transition midpoint years.

    values:
        Semantic-drift values.

    Returns
    -------
    dict
        Trend estimates and significance statistics.
    """

    valid_mask = (
        np.isfinite(years)
        & np.isfinite(values)
    )

    x = years[
        valid_mask
    ]

    y = values[
        valid_mask
    ]

    result = {
        "ols_slope": np.nan,
        "ols_intercept": np.nan,
        "ols_r": np.nan,
        "ols_r_squared": np.nan,
        "ols_p_value": np.nan,
        "ols_std_error": np.nan,
        "theil_sen_slope": np.nan,
        "theil_sen_intercept": np.nan,
        "theil_sen_low_slope": np.nan,
        "theil_sen_high_slope": np.nan,
        "kendall_tau": np.nan,
        "kendall_p_value": np.nan,
    }

    if len(x) < 2:
        return result

    if np.unique(x).size < 2:
        return result

    linear_result = linregress(
        x,
        y,
    )

    result.update(
        {
            "ols_slope": float(
                linear_result.slope
            ),
            "ols_intercept": float(
                linear_result.intercept
            ),
            "ols_r": float(
                linear_result.rvalue
            ),
            "ols_r_squared": float(
                linear_result.rvalue ** 2
            ),
            "ols_p_value": float(
                linear_result.pvalue
            ),
            "ols_std_error": float(
                linear_result.stderr
            ),
        }
    )

    try:

        (
            theil_slope,
            theil_intercept,
            low_slope,
            high_slope,
        ) = theilslopes(
            y,
            x,
            alpha=0.95,
        )

        result.update(
            {
                "theil_sen_slope": float(
                    theil_slope
                ),
                "theil_sen_intercept": float(
                    theil_intercept
                ),
                "theil_sen_low_slope": float(
                    low_slope
                ),
                "theil_sen_high_slope": float(
                    high_slope
                ),
            }
        )

    except ValueError:
        pass

    if len(x) >= 3:

        kendall_result = kendalltau(
            x,
            y,
            nan_policy="omit",
        )

        result.update(
            {
                "kendall_tau": float(
                    kendall_result.statistic
                ),
                "kendall_p_value": float(
                    kendall_result.pvalue
                ),
            }
        )

    return result


def classify_trend(
    slope: float,
    p_value: float,
    practical_threshold: float,
) -> str:
    """
    Classify trend direction using a robust slope,
    significance, and practical magnitude threshold.
    """

    if pd.isna(
        slope
    ):
        return "insufficient_data"

    if abs(slope) <= practical_threshold:
        return "stable"

    if (
        pd.notna(p_value)
        and p_value < SIGNIFICANCE_LEVEL
    ):

        if slope > 0:
            return "significant_increase"

        return "significant_decrease"

    if slope > 0:
        return "non_significant_increase"

    return "non_significant_decrease"


