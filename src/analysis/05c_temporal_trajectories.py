#!/usr/bin/env python3
"""
=========================================================
WP5 - Temporal Dynamics
05c_temporal_trajectories.py

Analyses company-level semantic-drift trajectories using
only consecutive one-year rolling-window transitions.

The script uses the corrected output generated by
05b_semantic_drift.py:

    semantic_drift_consecutive.parquet

It computes:

    1. Temporal trend estimates
       - Ordinary least-squares slope
       - Theil-Sen robust slope
       - Kendall rank trend
       - Trend significance and direction

    2. Temporal trajectory features
       - Rolling mean
       - Rolling median
       - Rolling standard deviation
       - Expanding mean
       - Expanding median
       - Cumulative semantic drift
       - Normalised cumulative drift
       - Transition-to-transition drift change

    3. Volatility and persistence
       - Mean absolute change
       - Root mean square change
       - Maximum absolute change
       - Lag-1 autocorrelation
       - Increasing/decreasing transition proportions
       - Longest increasing/decreasing runs

    4. Peak semantic-shift windows
       - Highest divergence transitions
       - Company-specific rank
       - Relative magnitude against company mean/median

    5. Change-point diagnostics
       - Extreme transition levels
       - Sudden transition-to-transition jumps
       - Robust z-scores
       - Combined change-point candidates

Important distinction
---------------------
An extreme transition is not automatically considered a
temporal change point.

A transition is classified as:

    extreme_transition
        Unusually large semantic-drift level.

    sudden_jump
        Unusually large change relative to the preceding
        transition.

    change_point_candidate
        Both an extreme transition and a sudden jump.

The first transition for each company cannot be labelled
as a sudden jump or change-point candidate because no
preceding transition exists.

Input:
    outputs/temporal/rolling5/
        semantic_drift_consecutive.parquet

Outputs:
    outputs/temporal/rolling5/
        semantic_drift_trajectories.parquet
        temporal_trajectory_summary.csv
        temporal_trajectory_rankings.csv
        temporal_trajectory_peaks.csv
        temporal_extreme_transitions.csv
        temporal_sudden_jumps.csv
        temporal_change_point_candidates.csv
=========================================================
"""

