def robust_z_scores(
    values: pd.Series,
) -> pd.Series:
    """
    Compute robust z-scores using the median absolute
    deviation.

    The standard consistency correction is used:

        z = 0.67448975 * (x - median) / MAD

    If the MAD is zero, an interquartile-range fallback is
    used. If both scales are zero, all finite observations
    receive a z-score of zero.

    Missing observations remain missing.
    """

    numeric_values = pd.to_numeric(
        values,
        errors="coerce",
    ).astype(float)

    result = pd.Series(
        np.nan,
        index=numeric_values.index,
        dtype=float,
    )

    finite_mask = np.isfinite(
        numeric_values
    )

    finite_values = numeric_values.loc[
        finite_mask
    ]

    if finite_values.empty:
        return result

    median_value = float(
        finite_values.median()
    )

    absolute_deviation = (
        finite_values - median_value
    ).abs()

    mad = float(
        absolute_deviation.median()
    )

    if mad > EPSILON:

        result.loc[finite_mask] = (
            0.67448975
            * (
                finite_values
                - median_value
            )
            / mad
        )

        return result

    q1 = float(
        finite_values.quantile(
            0.25
        )
    )

    q3 = float(
        finite_values.quantile(
            0.75
        )
    )

    iqr = q3 - q1

    if iqr > EPSILON:

        robust_scale = (
            iqr / 1.349
        )

        result.loc[finite_mask] = (
            finite_values
            - median_value
        ) / robust_scale

        return result

    result.loc[finite_mask] = 0.0

    return result


def safe_lag_one_autocorrelation(
    values: pd.Series,
) -> float:
    """
    Calculate lag-1 autocorrelation while safely handling
    short or constant trajectories.
    """

    clean_values = (
        pd.to_numeric(
            values,
            errors="coerce",
        )
        .dropna()
        .astype(float)
    )

    if len(clean_values) < 3:
        return np.nan

    if clean_values.nunique() <= 1:
        return np.nan

    autocorrelation = clean_values.autocorr(
        lag=1
    )

    if pd.isna(
        autocorrelation
    ):
        return np.nan

    return float(
        autocorrelation
    )


def longest_run(
    conditions: pd.Series,
) -> int:
    """
    Calculate the longest consecutive True run in a Boolean
    sequence.
    """

    longest = 0
    current = 0

    for condition in conditions.fillna(False):

        if bool(condition):
            current += 1
            longest = max(
                longest,
                current,
            )
        else:
            current = 0

    return int(
        longest
    )


