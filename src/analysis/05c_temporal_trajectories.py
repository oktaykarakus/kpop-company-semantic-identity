def split_phase_means(
    values: pd.Series,
) -> tuple[float, float, float]:
    """
    Divide a trajectory into three approximately equal
    temporal phases and return their mean drift values.
    """

    clean_values = (
        pd.to_numeric(
            values,
            errors="coerce",
        )
        .dropna()
        .reset_index(drop=True)
    )

    if clean_values.empty:
        return (
            np.nan,
            np.nan,
            np.nan,
        )

    phase_indices = np.array_split(
        np.arange(
            len(clean_values)
        ),
        3,
    )

    phase_means = []

    for indices in phase_indices:

        if len(indices) == 0:
            phase_means.append(
                np.nan
            )
        else:
            phase_means.append(
                float(
                    clean_values.iloc[
                        indices
                    ].mean()
                )
            )

    return tuple(
        phase_means
    )


def determine_dominant_phase(
    early_mean: float,
    middle_mean: float,
    late_mean: float,
) -> str:
    """
    Identify the broad temporal phase with the highest
    average semantic drift.
    """

    phase_values = {
        "early": early_mean,
        "middle": middle_mean,
        "late": late_mean,
    }

    valid_phases = {
        phase: value
        for phase, value in phase_values.items()
        if pd.notna(value)
    }

    if not valid_phases:
        return "undefined"

    return max(
        valid_phases,
        key=valid_phases.get,
    )


