def build_company_trajectory(
    company_df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Construct temporal trajectory features for one company.
    """

    trajectory = (
        company_df
        .sort_values(
            [
                "from_start",
                "to_start",
            ]
        )
        .reset_index(drop=True)
        .copy()
    )

    company = str(
        trajectory["company"].iloc[0]
    )

    validate_company_sequence(
        company_df=trajectory,
        company=company,
    )

    trajectory["sequence_index"] = (
        np.arange(
            1,
            len(trajectory) + 1,
        )
    )

    trajectory["midpoint_year"] = (
        trajectory["from_start"]
        + trajectory["to_start"]
    ) / 2.0

    drift_values = (
        trajectory["js_divergence"]
        .astype(float)
    )

    trajectory["drift_change"] = (
        drift_values.diff()
    )

    trajectory["absolute_drift_change"] = (
        trajectory["drift_change"]
        .abs()
    )

    trajectory["squared_drift_change"] = (
        trajectory["drift_change"] ** 2
    )

    trajectory["expanding_mean_js"] = (
        drift_values.expanding(
            min_periods=1
        ).mean()
    )

    trajectory["expanding_median_js"] = (
        drift_values.expanding(
            min_periods=1
        ).median()
    )

    trajectory["rolling_mean_js"] = (
        drift_values.rolling(
            window=ROLLING_WINDOW,
            min_periods=1,
            center=True,
        ).mean()
    )

    trajectory["rolling_median_js"] = (
        drift_values.rolling(
            window=ROLLING_WINDOW,
            min_periods=1,
            center=True,
        ).median()
    )

    trajectory["rolling_std_js"] = (
        drift_values.rolling(
            window=ROLLING_WINDOW,
            min_periods=2,
            center=True,
        ).std()
    )

    trajectory["cumulative_js"] = (
        drift_values.cumsum()
    )

    total_drift = float(
        drift_values.sum()
    )

    if total_drift > EPSILON:

        trajectory[
            "normalised_cumulative_js"
        ] = (
            trajectory["cumulative_js"]
            / total_drift
        )

    else:

        trajectory[
            "normalised_cumulative_js"
        ] = 0.0

    trajectory["robust_z_js"] = (
        robust_z_scores(
            drift_values
        )
    )

    trajectory["robust_z_change"] = (
        robust_z_scores(
            trajectory["drift_change"]
        )
    )

    trajectory["has_previous_transition"] = (
        trajectory["drift_change"].notna()
    )

    trajectory["is_extreme_transition"] = (
        trajectory["robust_z_js"]
        .abs()
        .ge(
            ROBUST_Z_THRESHOLD
        )
        .fillna(False)
    )

    trajectory["is_sudden_jump"] = (
        trajectory[
            "has_previous_transition"
        ]
        & trajectory[
            "robust_z_change"
        ]
        .abs()
        .ge(
            ROBUST_Z_THRESHOLD
        )
        .fillna(False)
    )

    trajectory[
        "is_change_point_candidate"
    ] = (
        trajectory[
            "is_extreme_transition"
        ]
        & trajectory[
            "is_sudden_jump"
        ]
    )

    trajectory["transition_classification"] = (
        "ordinary"
    )

    trajectory.loc[
        trajectory["is_extreme_transition"],
        "transition_classification",
    ] = "extreme_transition"

    trajectory.loc[
        trajectory["is_sudden_jump"],
        "transition_classification",
    ] = "sudden_jump"

    trajectory.loc[
        trajectory[
            "is_change_point_candidate"
        ],
        "transition_classification",
    ] = "change_point_candidate"

    trajectory["company_drift_rank"] = (
        drift_values.rank(
            method="dense",
            ascending=False,
        )
        .astype(int)
    )

    company_mean = float(
        drift_values.mean()
    )

    company_median = float(
        drift_values.median()
    )

    if company_mean > EPSILON:

        trajectory["relative_to_mean"] = (
            drift_values
            / company_mean
        )

    else:

        trajectory["relative_to_mean"] = np.nan

    if company_median > EPSILON:

        trajectory[
            "relative_to_median"
        ] = (
            drift_values
            / company_median
        )

    else:

        trajectory[
            "relative_to_median"
        ] = np.nan

    return trajectory


