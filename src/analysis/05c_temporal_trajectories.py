def validate_input(
    dataframe: pd.DataFrame,
) -> None:
    """
    Validate the consecutive semantic-drift dataframe.

    Parameters
    ----------
    dataframe:
        Consecutive semantic-drift transition dataframe.

    Raises
    ------
    ValueError
        If the dataframe is empty, required columns are
        missing, or irregular transitions are present.
    """

    required_columns = {
        "company",
        "from_window",
        "to_window",
        "from_start",
        "to_start",
        "year_gap",
        "is_consecutive",
        "js_divergence",
        "js_distance",
        "cosine_similarity",
        "cosine_distance",
        "euclidean_distance",
    }

    missing_columns = required_columns.difference(
        dataframe.columns
    )

    if missing_columns:
        missing_text = ", ".join(
            sorted(missing_columns)
        )

        raise ValueError(
            "Input file is missing required columns: "
            f"{missing_text}"
        )

    if dataframe.empty:
        raise ValueError(
            "The consecutive semantic-drift dataframe is "
            "empty."
        )

    if dataframe["company"].isna().any():
        raise ValueError(
            "The input dataframe contains missing company "
            "names."
        )

    if dataframe["is_consecutive"].isna().any():
        raise ValueError(
            "The input dataframe contains missing "
            "'is_consecutive' values."
        )

    if not dataframe["is_consecutive"].astype(bool).all():
        raise ValueError(
            "The input dataframe contains irregular "
            "transitions. This script must use only "
            "semantic_drift_consecutive.parquet."
        )

    if not (
        pd.to_numeric(
            dataframe["year_gap"],
            errors="coerce",
        ) == 1
    ).all():
        raise ValueError(
            "The input dataframe contains transitions with "
            "year_gap != 1."
        )


def validate_company_sequence(
    company_df: pd.DataFrame,
    company: str,
) -> None:
    """
    Validate the ordering and uniqueness of one company's
    transition sequence.
    """

    duplicate_transitions = (
        company_df[
            [
                "from_start",
                "to_start",
            ]
        ]
        .duplicated(
            keep=False
        )
    )

    if duplicate_transitions.any():
        duplicate_rows = (
            company_df.loc[
                duplicate_transitions,
                [
                    "from_start",
                    "to_start",
                ],
            ]
            .astype(str)
            .agg("->".join, axis=1)
            .tolist()
        )

        raise ValueError(
            f"Duplicate transitions detected for company "
            f"'{company}': {duplicate_rows}"
        )

    if len(company_df) < 2:
        return

    start_years = (
        company_df["from_start"]
        .to_numpy(dtype=int)
    )

    if np.any(
        np.diff(start_years) <= 0
    ):
        raise ValueError(
            "Transition start years are not strictly "
            f"increasing for company '{company}'."
        )


