def extract_peak_windows(
    trajectory_df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Extract the highest semantic-drift transitions for every
    company.
    """

    peak_rows = []

    for company, company_df in trajectory_df.groupby(
        "company",
        sort=True,
    ):

        ranked = (
            company_df
            .sort_values(
                [
                    "js_divergence",
                    "from_start",
                ],
                ascending=[
                    False,
                    True,
                ],
            )
            .head(
                TOP_PEAKS_PER_COMPANY
            )
            .copy()
        )

        ranked["peak_rank"] = (
            np.arange(
                1,
                len(ranked) + 1,
            )
        )

        peak_rows.append(
            ranked
        )

    selected_columns = [
        "company",
        "peak_rank",
        "from_window",
        "to_window",
        "from_start",
        "to_start",
        "midpoint_year",
        "js_distance",
        "js_divergence",
        "cosine_similarity",
        "cosine_distance",
        "euclidean_distance",
        "company_drift_rank",
        "relative_to_mean",
        "relative_to_median",
        "robust_z_js",
        "robust_z_change",
        "is_extreme_transition",
        "is_sudden_jump",
        "is_change_point_candidate",
        "transition_classification",
    ]

    if not peak_rows:
        return pd.DataFrame(
            columns=selected_columns
        )

    peaks = pd.concat(
        peak_rows,
        ignore_index=True,
    )

    return (
        peaks[
            selected_columns
        ]
        .sort_values(
            [
                "company",
                "peak_rank",
            ]
        )
        .reset_index(drop=True)
    )


def extract_flagged_transitions(
    trajectory_df: pd.DataFrame,
    flag_column: str,
) -> pd.DataFrame:
    """
    Extract transitions matching a Boolean diagnostic flag.
    """

    selected_columns = [
        "company",
        "from_window",
        "to_window",
        "from_start",
        "to_start",
        "midpoint_year",
        "sequence_index",
        "js_divergence",
        "drift_change",
        "absolute_drift_change",
        "robust_z_js",
        "robust_z_change",
        "company_drift_rank",
        "relative_to_mean",
        "relative_to_median",
        "is_extreme_transition",
        "is_sudden_jump",
        "is_change_point_candidate",
        "transition_classification",
    ]

    flagged = (
        trajectory_df.loc[
            trajectory_df[
                flag_column
            ].astype(bool)
        ]
        .copy()
    )

    if flagged.empty:
        return pd.DataFrame(
            columns=selected_columns
        )

    return (
        flagged[
            selected_columns
        ]
        .sort_values(
            [
                "company",
                "from_start",
            ]
        )
        .reset_index(drop=True)
    )


