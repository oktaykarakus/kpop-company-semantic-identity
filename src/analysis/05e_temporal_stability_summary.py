def extract_company_stable_periods(
    company_df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Extract all consecutive runs of transitions that were
    not detected as semantic change points.

    Parameters
    ----------
    company_df:
        Transition-level change-point data for one company.

    Returns
    -------
    pandas.DataFrame
        One row per stable run.
    """

    company_df = (
        company_df
        .sort_values(
            [
                "from_start",
                "to_start",
            ]
        )
        .reset_index(drop=True)
        .copy()
    )

    company = str(
        company_df["company"].iloc[0]
    )

    stable_rows = []

    current_indices = []

    period_number = 0

    def store_current_period(
        indices: list,
        period_id: int,
    ) -> None:
        """
        Store one completed stable run.
        """

        if not indices:
            return

        period_df = (
            company_df.loc[
                indices
            ]
            .sort_values(
                [
                    "from_start",
                    "to_start",
                ]
            )
        )

        first_row = period_df.iloc[0]

        last_row = period_df.iloc[-1]

        n_stable_transitions = int(
            len(period_df)
        )

        stable_year_span = int(
            last_row["to_start"]
            - first_row["from_start"]
        )

        stable_rows.append(
            {
                "company": company,
                "stable_period_number": int(
                    period_id
                ),
                "start_from_window": str(
                    first_row["from_window"]
                ),
                "end_to_window": str(
                    last_row["to_window"]
                ),
                "start_year": int(
                    first_row["from_start"]
                ),
                "end_year": int(
                    last_row["to_start"]
                ),
                "n_stable_transitions": (
                    n_stable_transitions
                ),
                "stable_year_span": (
                    stable_year_span
                ),
                "mean_js_during_period": float(
                    period_df[
                        "js_divergence"
                    ].mean()
                ),
                "median_js_during_period": float(
                    period_df[
                        "js_divergence"
                    ].median()
                ),
                "maximum_js_during_period": float(
                    period_df[
                        "js_divergence"
                    ].max()
                ),
                "minimum_js_during_period": float(
                    period_df[
                        "js_divergence"
                    ].min()
                ),
                "start_transition": str(
                    first_row["transition"]
                ),
                "end_transition": str(
                    last_row["transition"]
                ),
            }
        )

    for row_index, row in company_df.iterrows():

        is_change_point = bool(
            row["change_point"]
        )

        if not is_change_point:

            current_indices.append(
                row_index
            )

        elif current_indices:

            period_number += 1

            store_current_period(
                indices=current_indices,
                period_id=period_number,
            )

            current_indices = []

    if current_indices:

        period_number += 1

        store_current_period(
            indices=current_indices,
            period_id=period_number,
        )

    columns = [
        "company",
        "stable_period_number",
        "start_from_window",
        "end_to_window",
        "start_year",
        "end_year",
        "n_stable_transitions",
        "stable_year_span",
        "mean_js_during_period",
        "median_js_during_period",
        "maximum_js_during_period",
        "minimum_js_during_period",
        "start_transition",
        "end_transition",
    ]

    return pd.DataFrame(
        stable_rows,
        columns=columns,
    )


def extract_all_stable_periods(
    change_points: pd.DataFrame,
) -> pd.DataFrame:
    """
    Extract stable runs for all companies.
    """

    stable_period_frames = []

    for company, company_df in (
        change_points.groupby(
            "company",
            sort=True,
        )
    ):

        company_periods = (
            extract_company_stable_periods(
                company_df
            )
        )

        if not company_periods.empty:

            stable_period_frames.append(
                company_periods
            )

    if not stable_period_frames:

        return pd.DataFrame(
            columns=[
                "company",
                "stable_period_number",
                "start_from_window",
                "end_to_window",
                "start_year",
                "end_year",
                "n_stable_transitions",
                "stable_year_span",
                "mean_js_during_period",
                "median_js_during_period",
                "maximum_js_during_period",
                "minimum_js_during_period",
                "start_transition",
                "end_transition",
            ]
        )

    stable_periods = pd.concat(
        stable_period_frames,
        ignore_index=True,
    )

    return (
        stable_periods
        .sort_values(
            [
                "company",
                "start_year",
                "end_year",
            ]
        )
        .reset_index(drop=True)
    )


