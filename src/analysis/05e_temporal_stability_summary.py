def summarise_change_points(
    change_points: pd.DataFrame,
    stable_periods: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build one change-point and stable-period summary row per
    company.
    """

    summary_rows = []

    for company, company_df in (
        change_points.groupby(
            "company",
            sort=True,
        )
    ):

        company_df = (
            company_df
            .sort_values(
                [
                    "from_start",
                    "to_start",
                ]
            )
            .reset_index(drop=True)
        )

        detected = (
            company_df.loc[
                company_df["change_point"]
            ]
            .copy()
        )

        company_periods = (
            stable_periods.loc[
                stable_periods[
                    "company"
                ] == company
            ]
            .copy()
        )

        if detected.empty:

            largest_change_transition = ""

            largest_change_js = np.nan

            largest_change_robust_z = np.nan

            largest_change_severity = ""

            change_years = ""

        else:

            largest_change_row = (
                detected
                .sort_values(
                    [
                        "js_divergence",
                        "from_start",
                    ],
                    ascending=[
                        False,
                        True,
                    ],
                )
                .iloc[0]
            )

            chronological_detected = (
                detected
                .sort_values(
                    [
                        "from_start",
                        "to_start",
                    ]
                )
            )

            largest_change_transition = str(
                largest_change_row[
                    "transition"
                ]
            )

            largest_change_js = float(
                largest_change_row[
                    "js_divergence"
                ]
            )

            largest_change_robust_z = float(
                largest_change_row[
                    "robust_z"
                ]
            )

            largest_change_severity = str(
                largest_change_row[
                    "severity"
                ]
            )

            change_years = "|".join(
                chronological_detected[
                    "to_start"
                ]
                .astype(int)
                .astype(str)
                .tolist()
            )

        if company_periods.empty:

            n_stable_periods = 0

            longest_stable_transitions = 0

            longest_stable_year_span = 0

            longest_stable_start_year = np.nan

            longest_stable_end_year = np.nan

            longest_stable_start_window = ""

            longest_stable_end_window = ""

            longest_stable_mean_js = np.nan

        else:

            longest_period = (
                company_periods
                .sort_values(
                    [
                        "n_stable_transitions",
                        "stable_year_span",
                        "mean_js_during_period",
                        "start_year",
                    ],
                    ascending=[
                        False,
                        False,
                        True,
                        True,
                    ],
                )
                .iloc[0]
            )

            n_stable_periods = int(
                len(company_periods)
            )

            longest_stable_transitions = int(
                longest_period[
                    "n_stable_transitions"
                ]
            )

            longest_stable_year_span = int(
                longest_period[
                    "stable_year_span"
                ]
            )

            longest_stable_start_year = int(
                longest_period[
                    "start_year"
                ]
            )

            longest_stable_end_year = int(
                longest_period[
                    "end_year"
                ]
            )

            longest_stable_start_window = str(
                longest_period[
                    "start_from_window"
                ]
            )

            longest_stable_end_window = str(
                longest_period[
                    "end_to_window"
                ]
            )

            longest_stable_mean_js = float(
                longest_period[
                    "mean_js_during_period"
                ]
            )

        n_transitions = int(
            len(company_df)
        )

        n_change_points = int(
            detected.shape[0]
        )

        n_stable_transitions = (
            n_transitions
            - n_change_points
        )

        summary_rows.append(
            {
                "company": company,
                "n_transitions": n_transitions,
                "n_change_points": (
                    n_change_points
                ),
                "change_point_rate": float(
                    n_change_points
                    / n_transitions
                ),
                "n_stable_transitions": int(
                    n_stable_transitions
                ),
                "stable_transition_rate": float(
                    n_stable_transitions
                    / n_transitions
                ),
                "n_stable_periods": (
                    n_stable_periods
                ),
                "longest_stable_transitions": (
                    longest_stable_transitions
                ),
                "longest_stable_year_span": (
                    longest_stable_year_span
                ),
                "longest_stable_start_year": (
                    longest_stable_start_year
                ),
                "longest_stable_end_year": (
                    longest_stable_end_year
                ),
                "longest_stable_start_window": (
                    longest_stable_start_window
                ),
                "longest_stable_end_window": (
                    longest_stable_end_window
                ),
                "longest_stable_mean_js": (
                    longest_stable_mean_js
                ),
                "largest_change_transition": (
                    largest_change_transition
                ),
                "largest_change_js": (
                    largest_change_js
                ),
                "largest_change_robust_z": (
                    largest_change_robust_z
                ),
                "largest_change_severity": (
                    largest_change_severity
                ),
                "change_years": change_years,
            }
        )

    return pd.DataFrame(
        summary_rows
    )


