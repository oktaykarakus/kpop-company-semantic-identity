def build_final_summary(
    drift_summary: pd.DataFrame,
    change_summary: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Merge drift and change-point statistics, calculate the
    stability index, and prepare final ranked outputs.
    """

    merged = drift_summary.merge(
        change_summary,
        on=[
            "company",
            "n_transitions",
        ],
        how="inner",
        validate="one_to_one",
    )

    if len(merged) != len(
        drift_summary
    ):
        raise ValueError(
            "Not all company rows could be merged between "
            "the 05b and 05d outputs."
        )

    (
        indexed_summary,
        method_table,
    ) = add_stability_index(
        merged
    )

    final_columns = [
        "company",
        "n_transitions",
        "mean_js",
        "median_js",
        "std_js",
        "cv_js",
        "min_js",
        "q1_js",
        "q3_js",
        "iqr_js",
        "max_js",
        "mean_js_distance",
        "mean_cosine",
        "mean_cosine_distance",
        "mean_euclidean",
        "n_change_points",
        "change_point_rate",
        "n_stable_transitions",
        "stable_transition_rate",
        "n_stable_periods",
        "longest_stable_transitions",
        "longest_stable_year_span",
        "longest_stable_start_year",
        "longest_stable_end_year",
        "longest_stable_start_window",
        "longest_stable_end_window",
        "longest_stable_mean_js",
        "largest_change_transition",
        "largest_change_js",
        "largest_change_robust_z",
        "largest_change_severity",
        "change_years",
        "normalised_mean_js",
        "normalised_std_js",
        "normalised_max_js",
        "normalised_change_point_rate",
        "relative_instability_score",
        "stability_index",
        "stability_rank",
        "stability_category",
    ]

    final_summary = (
        indexed_summary[
            final_columns
        ]
        .sort_values(
            "company"
        )
        .reset_index(drop=True)
    )

    ranking = (
        final_summary
        .sort_values(
            [
                "stability_rank",
                "stability_index",
                "mean_js",
            ],
            ascending=[
                True,
                False,
                True,
            ],
        )
        .reset_index(drop=True)
    )

    return (
        final_summary,
        ranking,
        method_table,
    )


