def min_max_normalise(
    values: pd.Series,
) -> tuple[pd.Series, float, float]:
    """
    Min-max normalise a company-level instability metric.

    If all companies have the same value, the normalised
    component is set to zero for every company because the
    metric provides no discriminating information.
    """

    numeric_values = pd.to_numeric(
        values,
        errors="raise",
    ).astype(float)

    minimum_value = float(
        numeric_values.min()
    )

    maximum_value = float(
        numeric_values.max()
    )

    value_range = (
        maximum_value
        - minimum_value
    )

    if value_range <= EPSILON:

        normalised = pd.Series(
            0.0,
            index=numeric_values.index,
            dtype=float,
        )

    else:

        normalised = (
            numeric_values
            - minimum_value
        ) / value_range

    return (
        normalised,
        minimum_value,
        maximum_value,
    )


def add_stability_index(
    summary: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Add the relative temporal stability index and create a
    method table describing its components.
    """

    result = summary.copy()

    method_rows = []

    normalised_columns = []

    for component in STABILITY_COMPONENTS:

        normalised_column = (
            f"normalised_{component}"
        )

        (
            normalised_values,
            minimum_value,
            maximum_value,
        ) = min_max_normalise(
            result[component]
        )

        result[normalised_column] = (
            normalised_values
        )

        normalised_columns.append(
            normalised_column
        )

        method_rows.append(
            {
                "component": component,
                "interpretation": (
                    "higher_value_indicates_instability"
                ),
                "weight": float(
                    1.0
                    / len(
                        STABILITY_COMPONENTS
                    )
                ),
                "normalisation": (
                    "cross_company_min_max"
                ),
                "observed_minimum": (
                    minimum_value
                ),
                "observed_maximum": (
                    maximum_value
                ),
            }
        )

    result[
        "relative_instability_score"
    ] = (
        result[
            normalised_columns
        ]
        .mean(axis=1)
    )

    result[
        "stability_index"
    ] = (
        100.0
        * (
            1.0
            - result[
                "relative_instability_score"
            ]
        )
    )

    result["stability_index"] = (
        result["stability_index"]
        .clip(
            lower=0.0,
            upper=100.0,
        )
    )

    result["stability_rank"] = (
        result["stability_index"]
        .rank(
            method="min",
            ascending=False,
        )
        .astype(int)
    )

    result["stability_category"] = (
        result["stability_rank"]
        .map(
            classify_stability_rank
        )
    )

    method_table = pd.DataFrame(
        method_rows
    )

    return (
        result,
        method_table,
    )


def classify_stability_rank(
    rank: int,
) -> str:
    """
    Assign an ordinal descriptive stability category based
    on the final company ranking.
    """

    rank = int(
        rank
    )

    if rank == 1:
        return "most_stable"

    if rank == 2:
        return "relatively_stable"

    if rank == 3:
        return "relatively_dynamic"

    return "most_dynamic"


