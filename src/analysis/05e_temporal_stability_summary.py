#!/usr/bin/env python3
"""
=========================================================
WP5 - Temporal Dynamics
05e_temporal_stability_summary.py

Scientific question
-------------------
Which entertainment companies exhibit the most stable
long-term semantic identities?

This script combines the corrected consecutive-transition
semantic-drift statistics from 05b with the robust semantic
change-point results from 05d.

It produces one publication-quality company-level table
summarising:

    - Mean Jensen-Shannon divergence
    - Median Jensen-Shannon divergence
    - Standard deviation
    - Coefficient of variation
    - Minimum and maximum drift
    - Interquartile range
    - Mean cosine similarity
    - Mean Euclidean distance
    - Number and rate of detected change points
    - Largest detected change point
    - Longest stable period
    - Relative temporal stability index
    - Final stability rank and category

Longest stable period
---------------------
A stable period is defined as a consecutive sequence of
rolling-window transitions that were not identified as
semantic change points by 05d.

Because the input contains one-year consecutive rolling
transitions, the number of stable transitions is also the
length of the corresponding start-year span.

Relative stability index
------------------------
The final stability index is a descriptive relative composite
rather than an inferential statistic.

Four instability indicators are used:

    1. Mean JS divergence
    2. Standard deviation of JS divergence
    3. Maximum JS divergence
    4. Change-point rate

Each indicator is min-max normalised across the analysed
companies:

    normalised_x =
        (x - minimum_x) / (maximum_x - minimum_x)

The relative instability score is the arithmetic mean of
the four normalised indicators.

The relative stability index is:

    stability_index =
        100 * (1 - relative_instability_score)

Therefore:

    100 = most stable observed temporal profile
      0 = least stable observed temporal profile

The index is explicitly relative to the companies included
in the analysis. It should not be interpreted as an absolute
or universal measure of semantic stability.

Input
-----
outputs/temporal/rolling5/
    semantic_drift_summary_consecutive.csv
    semantic_change_points.csv

Outputs
-------
outputs/temporal/rolling5/
    temporal_stability_summary.csv
    temporal_stability_rankings.csv
    temporal_stable_periods.csv
    temporal_stability_method.csv
=========================================================
"""

