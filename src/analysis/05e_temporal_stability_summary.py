def validate_drift_summary(
    dataframe: pd.DataFrame,
) -> None:
    """
    Validate the corrected consecutive-transition drift
    summary generated by 05b.
    """

    required_columns = {
        "company",
        "n_transitions",
        "mean_js",
        "median_js",
        "std_js",
        "cv_js",
        "min_js",
        "q1_js",
        "q3_js",
        "iqr_js",
        "max_js",
        "mean_js_distance",
        "mean_annualised_js",
        "median_annualised_js",
        "mean_cosine",
        "mean_cosine_distance",
        "mean_euclidean",
    }

    missing_columns = required_columns.difference(
        dataframe.columns
    )

    if missing_columns:
        missing_text = ", ".join(
            sorted(missing_columns)
        )

        raise ValueError(
            "Drift-summary file is missing required "
            f"columns: {missing_text}"
        )

    if dataframe.empty:
        raise ValueError(
            "The consecutive-transition drift summary is "
            "empty."
        )

    if dataframe["company"].duplicated().any():
        duplicated_companies = (
            dataframe.loc[
                dataframe["company"].duplicated(
                    keep=False
                ),
                "company",
            ]
            .astype(str)
            .unique()
            .tolist()
        )

        raise ValueError(
            "Duplicate company rows found in the drift "
            f"summary: {duplicated_companies}"
        )


def validate_change_points(
    dataframe: pd.DataFrame,
) -> None:
    """
    Validate transition-level change-point results generated
    by 05d.
    """

    required_columns = {
        "company",
        "transition",
        "from_window",
        "to_window",
        "from_start",
        "to_start",
        "year_gap",
        "js_divergence",
        "threshold",
        "robust_z",
        "change_point",
        "severity",
    }

    missing_columns = required_columns.difference(
        dataframe.columns
    )

    if missing_columns:
        missing_text = ", ".join(
            sorted(missing_columns)
        )

        raise ValueError(
            "Change-point file is missing required "
            f"columns: {missing_text}"
        )

    if dataframe.empty:
        raise ValueError(
            "The semantic change-point dataframe is empty."
        )

    if not (
        pd.to_numeric(
            dataframe["year_gap"],
            errors="coerce",
        ) == 1
    ).all():
        raise ValueError(
            "The semantic change-point file contains "
            "non-consecutive transitions."
        )

    duplicate_transitions = (
        dataframe[
            [
                "company",
                "from_start",
                "to_start",
            ]
        ]
        .duplicated(
            keep=False
        )
    )

    if duplicate_transitions.any():
        raise ValueError(
            "Duplicate company-transition rows were found "
            "in the semantic change-point file."
        )


def validate_company_alignment(
    drift_summary: pd.DataFrame,
    change_points: pd.DataFrame,
) -> None:
    """
    Confirm that both inputs contain the same companies and
    transition counts.
    """

    drift_companies = set(
        drift_summary["company"]
        .astype(str)
        .unique()
    )

    change_companies = set(
        change_points["company"]
        .astype(str)
        .unique()
    )

    if drift_companies != change_companies:

        only_in_drift = sorted(
            drift_companies
            - change_companies
        )

        only_in_change = sorted(
            change_companies
            - drift_companies
        )

        raise ValueError(
            "Company mismatch between 05b and 05d outputs. "
            f"Only in drift summary: {only_in_drift}; "
            f"only in change points: {only_in_change}"
        )

    observed_counts = (
        change_points.groupby(
            "company"
        )
        .size()
        .rename(
            "observed_n_transitions"
        )
        .reset_index()
    )

    expected_counts = (
        drift_summary[
            [
                "company",
                "n_transitions",
            ]
        ]
        .copy()
    )

    comparison = expected_counts.merge(
        observed_counts,
        on="company",
        how="left",
        validate="one_to_one",
    )

    count_mismatch = (
        comparison["n_transitions"]
        .astype(int)
        != comparison[
            "observed_n_transitions"
        ].astype(int)
    )

    if count_mismatch.any():

        mismatch_rows = comparison.loc[
            count_mismatch
        ].to_dict(
            orient="records"
        )

        raise ValueError(
            "Transition counts differ between 05b and 05d "
            f"outputs: {mismatch_rows}"
        )


